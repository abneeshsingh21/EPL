def generate_azure_containerapp(app_name: str, image: str,
                                  port: int = 8000,
                                  region: str = "eastus") -> str:
    """Generate Azure Container Apps YAML config."""
    return textwrap.dedent(f"""\
        # Azure Container Apps configuration for {app_name}
        # Generated by EPL Cloud Deploy
        #
        # Usage: az containerapp create --yaml containerapp.yaml

        name: {app_name}
        location: {region}
        resourceGroup: {app_name}-rg
        type: Microsoft.App/containerApps
        properties:
          managedEnvironmentId: /subscriptions/YOUR_SUBSCRIPTION_ID/resourceGroups/{app_name}-rg/providers/Microsoft.App/managedEnvironments/{app_name}-env
          configuration:
            ingress:
              external: true
              targetPort: {port}
              transport: http
            registries: []
          template:
            containers:
              - name: {app_name}
                image: {image}
                resources:
                  cpu: 0.5
                  memory: 1Gi
                env:
                  - name: EPL_ENV
                    value: production
                  - name: EPL_PORT
                    value: "{port}"
            scale:
              minReplicas: 1
              maxReplicas: 10
              rules:
                - name: http-scaling
                  http:
                    metadata:
                      concurrentRequests: "100"
    """)


def generate_azure_deploy_script(app_name: str, image: str,
                                   region: str = "eastus",
                                   port: int = 8000) -> str:
    """Generate Azure CLI deploy script."""
    return textwrap.dedent(f"""\
        #!/bin/bash
        # Azure Container Apps Deploy Script for {app_name}
        # Generated by EPL Cloud Deploy
        #
        # Usage: chmod +x azure-deploy.sh && ./azure-deploy.sh

        set -e

        APP_NAME="{app_name}"
        IMAGE="{image}"
        REGION="{region}"
        RESOURCE_GROUP="${{APP_NAME}}-rg"
        ENVIRONMENT="${{APP_NAME}}-env"
        PORT="{port}"

        echo "Creating resource group..."
        az group create --name $RESOURCE_GROUP --location $REGION

        echo "Creating Container Apps environment..."
        az containerapp env create \\
            --name $ENVIRONMENT \\
            --resource-group $RESOURCE_GROUP \\
            --location $REGION

        echo "Deploying container app..."
        az containerapp create \\
            --name $APP_NAME \\
            --resource-group $RESOURCE_GROUP \\
            --environment $ENVIRONMENT \\
            --image $IMAGE \\
            --target-port $PORT \\
            --ingress external \\
            --min-replicas 1 \\
            --max-replicas 10 \\
            --env-vars EPL_ENV=production EPL_PORT=$PORT

        echo "Getting app URL..."
        az containerapp show \\
            --name $APP_NAME \\
            --resource-group $RESOURCE_GROUP \\
            --query properties.configuration.ingress.fqdn \\
            --output tsv

        echo "Deployment complete!"
    """)


def generate_azure_all(app_name: str, image: str,
                        output_dir: str = "./deploy/azure",
                        port: int = 8000,
                        region: str = "eastus") -> list:
    """Generate all Azure deployment files."""
